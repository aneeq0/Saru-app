function stockRow(
  id: string,
  sku: string,
  productName: string,
  variantName: string,
  warehouseId: string,
  warehouseName: string,
  onHand: number,
  reserved: number,
  unit: string,
  extras?: Partial<StockBalance>,
): StockBalance {
  const quarantined = extras?.quarantined ?? 0
  const damaged = extras?.damaged ?? 0
  const expired = extras?.expired ?? 0
  const available = Math.max(0, onHand - reserved - quarantined - damaged - expired)
  return {
    id,
    sku,
    productName,
    variantName,
    warehouseId,
    warehouseName,
    onHand,
    reserved,
    available,
    quarantined,
    damaged,
    expired,
    unit,
    ...extras,
  }
}

